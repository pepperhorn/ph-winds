// Generate the standalone `@pepperhorn/fingering-components` preview page into
// `public/components-preview.html`, where `src/pages/components.astro` embeds it
// in an iframe (an iframe so the library's own `--fc-*` CSS and Google-hosted
// Poppins stay isolated from global.css/Tailwind).
//
// The generator lives in the library, not here: it reads that package's own
// `src/*.js`, `instruments/*.json` and `fingerings/*.json` and emits one
// self-contained ~128 kB HTML file with the JS and CSS inlined. So the preview
// always matches the installed version of the library, and there is nothing to
// keep in sync on this side. The output is a build artifact: it is gitignored
// and regenerated by `prebuild`.
//
// Resolution goes through the package's `./build-preview` export rather than a
// hardcoded path into node_modules, and the generator runs as a child process
// because it is a bin-style script that writes on import and takes the output
// path as `process.argv[2]`.

import { createRequire } from 'node:module';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const PACKAGE = '@pepperhorn/fingering-components';
const SUBPATH = `${PACKAGE}/build-preview`;
const MIN_VERSION = '0.2.1';

const require = createRequire(import.meta.url);
const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(repoRoot, 'public', 'components-preview.html');

const installedVersion = () => {
  try {
    return require(`${PACKAGE}/package.json`).version;
  } catch {
    return 'not installed';
  }
};

const fail = (why) => {
  console.error(
    [
      `\nCannot generate public/components-preview.html: ${why}`,
      '',
      `  required: ${PACKAGE} >= ${MIN_VERSION} (exposes "${SUBPATH}" and the "fingering-preview" bin)`,
      `  installed: ${installedVersion()}`,
      '',
      `Bump the dependency and reinstall:  pnpm add ${PACKAGE}@^${MIN_VERSION}`,
      '',
    ].join('\n'),
  );
  process.exit(1);
};

let generator;
try {
  generator = require.resolve(SUBPATH);
} catch (err) {
  fail(`the installed ${PACKAGE} does not export "${SUBPATH}" (${err.code ?? err.message}).`);
}

const result = spawnSync(process.execPath, [generator, out], { stdio: 'inherit' });

if (result.error) fail(`running the generator failed (${result.error.message}).`);
if (result.status !== 0) fail(`the generator exited with code ${result.status}.`);
