// Generate src/notation/verovio-font-{bravura,petaluma}.generated.ts — embeds
// each bundled Verovio font zip as base64, one module per font, so the app can
// dynamically import only the font it actually needs at first use (mirroring
// the woff2 embedding in src/staff-fonts.ts).
//
// Regenerate after rebuilding the zips: node scripts/embed-verovio-fonts.mjs
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const fontsDir = join(here, "..", "fonts", "verovio");
const notationDir = join(here, "..", "src", "notation");

async function b64(name) {
  return (await readFile(join(fontsDir, name))).toString("base64");
}

const header = `// AUTO-GENERATED by scripts/embed-verovio-fonts.mjs — do not edit by hand.
// Base64 of the bundled Verovio custom-font zip (fonts/verovio/${"NAME"}.zip).
// Loaded via Verovio's \`fontAddCustom\` option so the app engraves with the
// repo-bundled font rather than whatever the Verovio build embeds.
//
// Exports a uniform \`ZIP_B64\` name (rather than a per-font constant name)
// so the dynamic \`import()\` in src/notation/verovio.ts can be typed exactly
// as \`Promise<{ ZIP_B64: string }>\` instead of a loosely-typed string-keyed
// record.
/* eslint-disable */
`;

const fonts = [
  { name: "Bravura", zip: "Bravura.zip", file: "verovio-font-bravura.generated.ts" },
  { name: "Petaluma", zip: "Petaluma.zip", file: "verovio-font-petaluma.generated.ts" },
];

for (const font of fonts) {
  const b64Data = await b64(font.zip);
  const body =
    header.replace("NAME", font.name) +
    `export const ZIP_B64 = ${JSON.stringify(b64Data)};\n`;
  const out = join(notationDir, font.file);
  await writeFile(out, body);
  console.log(`wrote ${out} (${(body.length / 1024).toFixed(0)} KB)`);
}
